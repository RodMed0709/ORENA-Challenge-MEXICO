"""Probe 16d — the systematic finder: where does OUR fine-tuning emit SDK-illegal answers?

## The generalisation of the `"1."` finding

16a asked an off-template question and the fine-tuned checkpoint answered `"1."` — with a
trailing period — on **87%** of `number` questions. `Number.verify` gates on
`str.strip().isdigit()`, so every one of those is **auto-incorrect**. The base model's rate on
the same probe is **0.0000**: we created the fragility.

That was luck. This module makes it a sweep.

## Why it is nearly free, and why nobody found it earlier

🟢 **`sdk_valid` needs no ground truth.** "Would the SDK's verifier accept this string?" is a
property of the model's OUTPUT alone. So we can audit any phrasing we like — including phrasings
we have no gold for — without annotating anything. That is what turns this from an experiment
into a sweep.

🔴 **And it is why the defect was invisible.** Our scored eval only ever asks the corpus's own
templates. A formatting fragility that lives *outside* those templates cannot show up in any
number we report, by construction. The hidden test is generated by the organizers, not by us,
and `open-class-vocabulary.md` already records a possible train/test regime mismatch (70% of our
questions lack the class list the spec says they carry). So the blind spot is not hypothetical.

## Design

For each `answer_format`, take REAL corpus questions and ask them under controlled surface
variants. The meaning is preserved; only the wording moves. Then measure, per
(model × format × variant), the rate of SDK-illegal answers and *which* violation occurred.

`v0` is the corpus question verbatim — the control. If `v0` is clean and `v1..vN` are not, the
fragility is phrasing-induced and our scored eval cannot see it.

⚠️ **This measures format legality, NOT correctness.** An answer can be perfectly formatted and
wrong. Read it as a floor on lost points: every illegal answer is scored wrong *regardless* of
whether the model knew the answer.
"""

from __future__ import annotations

import logging
import re

logger = logging.getLogger(__name__)

# Surface variants. Each is a callable question -> question. They must preserve MEANING —
# a variant that changes what is asked measures the wrong thing.
VARIANTS: dict[str, callable] = {
    "v0_verbatim": lambda q: q,
    "v1_in_frame": lambda q: q.rstrip("?. ") + " in this frame?",
    "v2_imperative": lambda q: re.sub(r"^How many\b", "State the number of", q, flags=re.I).rstrip("?") + ".",
    "v3_polite": lambda q: q.rstrip() + " Please respond with the answer only.",
    "v4_lowercase": lambda q: q[:1].lower() + q[1:],
    "v5_no_qmark": lambda q: q.rstrip("? "),
}

# The SDK's actual gates, mirrored. Keep these in lockstep with `focus.formats` — the whole
# point is to predict what the verifier will do, so a divergence here is a silent lie.
#   number  -> str.strip().isdigit()          (CONSTITUTION §I.4)
#   binary  -> the SDK compares against yes/no
#   fo_class-> set-equality, case-insensitive, against FOType.names(); an unknown token RAISES
_INT = re.compile(r"^\d+$")


def _class_vocab_lower() -> set[str]:
    from focus.foreign_objects import FOType

    return {n.lower() for n in FOType.names()}


def sdk_legal(answer: str, fmt: str) -> tuple[bool, str]:
    """(is_legal, violation_tag). `violation_tag` is "" when legal.

    The tag is the product: it names WHAT the model did wrong, so the sweep produces a
    fixable list rather than a rate.
    """
    s = (answer or "").strip()
    if not s:
        return False, "empty"

    if fmt == "number":
        if _INT.match(s):
            return True, ""
        if re.match(r"^\d+\s*\.$", s):
            return False, "trailing_period"
        if re.match(r"^\d+\s*[a-zA-Z]", s):
            return False, "number_plus_unit"
        if re.match(r"^\d+[.,]\d+$", s):
            return False, "decimal"
        if re.search(r"\d", s):
            return False, "number_in_prose"
        return False, "no_digits"

    if fmt == "binary":
        if s.lower() in {"yes", "no"}:
            return True, ""
        if re.match(r"^(yes|no)\b", s, re.I):
            return False, "yesno_plus_text"
        return False, "not_yesno"

    if fmt == "fo_class":
        vocab = _class_vocab_lower()
        toks = [t.strip().lower() for t in s.split(",") if t.strip()]
        if not toks:
            return False, "empty"
        unknown = [t for t in toks if t not in vocab and t != "none"]
        if unknown:
            # 🔴 RULES §8b: an unrecognised token does not merely score 0 — FOType.from_name()
            # RAISES, and `foreign object` (offered in the organizers' in-prompt list) is NOT
            # in FOType.names().
            return False, f"unknown_class:{unknown[0][:24]}"
        if s != s.strip() or "  " in s:
            return False, "whitespace"
        return True, ""

    # multiple_choice / open_ended go to the LLM judge; there is no exact gate to mirror, so
    # report only the crude cap the SDK enforces.
    if len(s) > 300:
        return False, "over_300_chars"
    return True, ""


def select_by_format(items, fmt: str, n: int, seed: int = 0):
    """`n` real corpus questions of one format, deterministic, spread across videos."""
    import random

    from zero_probe import answer_format

    pool = [it for it in items if answer_format(it.reference) == fmt]
    # spread across videos so the audit is not one video's phrasing quirk
    by_vid: dict[str, list] = {}
    for it in pool:
        by_vid.setdefault(it.video_id, []).append(it)
    rng = random.Random(seed)
    vids = sorted(by_vid)
    rng.shuffle(vids)
    out = []
    while len(out) < n and any(by_vid[v] for v in vids):
        for v in vids:
            if by_vid[v] and len(out) < n:
                out.append(by_vid[v].pop())
    logger.info("format %s: %d items over %d videos", fmt, len(out), len({i.video_id for i in out}))
    return out


def run_audit(engine, items_by_fmt: dict[str, list], model_tag: str,
              variants: dict | None = None, log_every: int = 100) -> list[dict]:
    """Ask every selected question under every variant. Returns flat rows."""
    from PIL import Image

    from frame.data import frame_cache_name

    variants = variants or VARIANTS
    rows: list[dict] = []
    total = sum(len(v) for v in items_by_fmt.values()) * len(variants)
    i = 0
    for fmt, items in items_by_fmt.items():
        for it in items:
            key = frame_cache_name(it)
            path = f"/workspace/frames_cache/{key}"
            base_q = str(it.request.question)
            for vname, fn in variants.items():
                q = fn(base_q)
                try:
                    with Image.open(path) as im:
                        raw = engine.predict(im.convert("RGB"), q)
                except Exception as exc:
                    logger.warning("audit %s/%s failed: %s", key, vname, exc)
                    raw = ""
                legal, viol = sdk_legal(raw, fmt)
                rows.append(
                    {
                        "model": model_tag,
                        "fmt": fmt,
                        "variant": vname,
                        "frame_key": key,
                        "video_id": it.video_id,
                        "distribution": "OOD" if it.dataset == "heico" else "ID",
                        "question": q,
                        "raw": (raw or "").strip()[:120],
                        "sdk_legal": legal,
                        "violation": viol,
                    }
                )
                i += 1
                if i % log_every == 0:
                    logger.info("  %s: %d/%d", model_tag, i, total)
    return rows


def score(rows: list[dict]) -> dict:
    """Illegal-answer rate per (model, format, variant), plus the violation histogram."""
    out: dict[str, dict] = {}
    keys = sorted({(r["model"], r["fmt"], r["variant"]) for r in rows})
    for mdl, fmt, var in keys:
        sel = [r for r in rows if r["model"] == mdl and r["fmt"] == fmt and r["variant"] == var]
        illegal = [r for r in sel if not r["sdk_legal"]]
        hist: dict[str, int] = {}
        for r in illegal:
            hist[r["violation"]] = hist.get(r["violation"], 0) + 1
        out[f"{mdl}|{fmt}|{var}"] = {
            "n": len(sel),
            "illegal_rate": len(illegal) / len(sel) if sel else float("nan"),
            "top_violation": max(hist, key=hist.get) if hist else "",
            "violations": hist,
        }
    return out


def regressions(scored: dict, control: str = "v0_verbatim", min_delta: float = 0.10) -> list[dict]:
    """The product of this probe: where `ft` is MORE illegal than `base`, or than its own v0.

    Two comparisons, because they mean different things:
      * `vs_base`  — did OUR fine-tuning introduce it? (the `"1."` case: ft 0.87 vs base 0.00)
      * `vs_v0`    — is it phrasing-induced, i.e. invisible to our template-only scored eval?
    """
    rows = []
    for key, val in scored.items():
        mdl, fmt, var = key.split("|")
        if mdl != "ft":
            continue
        base = scored.get(f"base|{fmt}|{var}", {}).get("illegal_rate")
        own0 = scored.get(f"ft|{fmt}|{control}", {}).get("illegal_rate")
        d_base = None if base is None else val["illegal_rate"] - base
        d_v0 = None if own0 is None else val["illegal_rate"] - own0
        if (d_base is not None and d_base >= min_delta) or (d_v0 is not None and d_v0 >= min_delta):
            rows.append(
                {
                    "fmt": fmt,
                    "variant": var,
                    "ft_illegal": round(val["illegal_rate"], 4),
                    "base_illegal": None if base is None else round(base, 4),
                    "delta_vs_base": None if d_base is None else round(d_base, 4),
                    "delta_vs_own_v0": None if d_v0 is None else round(d_v0, 4),
                    "top_violation": val["top_violation"],
                }
            )
    return sorted(rows, key=lambda r: -(r["delta_vs_base"] or r["delta_vs_own_v0"] or 0))

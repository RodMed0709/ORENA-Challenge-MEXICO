"""Rung 61 — promote ALL 38 test videos into training. The corpus is the variable.

Rung 42 promoted 30 of 38 and held 8 back so the campaign would keep a local eval. That
eval has now said everything it is going to say, and what it said last was that it INVERTS
against the platform on both OOD halves (object_recognition local 0.8246 vs platform
0.4805; aggregation local 0.4133 vs platform 0.6011). The pre-eval is closed. Every read
left is a submission. So the 8 videos stop being an instrument and go back to being data.

    rung 42 corpus  19,384 rows = rung 18's 14,415 + 4,969 from 30 promoted videos
    rung 61 corpus  20,667 rows = the same 19,384 + 1,283 from the 8 that were held

⇒ The ONLY difference from the arm that shipped as submission 03 (0.5809) and 06 (0.58128)
is `--dataset` (gate G3), and inside `--dataset` the only difference is +1,283 rows of the
same distribution, generated by a builder that reproduces the shipped 4,969 BYTE FOR BYTE
(`RESULTS_build61.json`, gate 1).

🔴 THE PRICE, stated before the run rather than discovered after it. This corpus destroys
every local eval we own. All 38 test videos are in training; `bucket_mean` on the 1,283
becomes a memorisation readout and MUST NOT be quoted. The rung-48 centre probe still reads
(CholecT50 is untouched) but it orders, it does not scale. The verdict is the platform.

⚠️ And the honest risk: rung 42's +0.0402 came from promoting 30 videos, of which 3,200
rows were Sigmoid — a procedure with ZERO training videos. The remaining 8 add no new
procedure and no new centre. This is the same lever at 26 % of the stroke, on a model that
has already had it. A null is the likely outcome and gets published as one.

⚠️ WALL CLOCK. 20,667 / 16 = 1,292 steps per epoch, 6,459 for five. At rung 57's measured
~16.5 s/it that is ~29.6 h; ep4 lands at ~23.7 h. `--save_strategy epoch` means every epoch
stands alone. Deadline is Sep 11, so ep4 has ~4 days of margin.
"""
import csv
import json
import os
import subprocess
import sys
import time
from dataclasses import replace
from pathlib import Path

# Two boxes run this rung and their layouts share nothing, so every path is an env override
# with the UNAM layout as the default. One script, no second copy to drift.
#
# 🔴 On UNAM, /data — and therefore ~/storage — is a DANGLING symlink since the 18-Aug reboot
# (no fstab entry). Absolute /mnt paths only there.
# 📌 On the RunPod volume the corpus is rung 42's OWN train.jsonl, the literal bytes it
# trained on, so that box needs no rebuild and carries better provenance than any copy.
STORE = Path(os.environ.get("RUNG61_STORE", "/mnt/storage/uaq_user"))
REPO = Path(os.environ.get("RUNG61_REPO", str(STORE / "repo_rod")))
RUNG = Path(os.environ.get("RUNG61_RUNG", str(STORE / "rung61")))
MODEL = Path(os.environ.get(
    "RUNG61_MODEL",
    str(STORE / "hf_cache/hub/models--Qwen--Qwen3-VL-8B-Instruct/snapshots"
              "/0c351dd01ed87e9c1b53cbc748cba10e6187ff3b")))

CORPUS = Path(os.environ.get("RUNG61_CORPUS", str(RUNG / "corpus/train_all38.jsonl")))
# The two boxes hold the same 19,384 rows with different absolute image paths, so the bytes —
# and therefore the digest — legitimately differ. Both are pinned; neither is free-floating.
CORPUS_SHA = os.environ.get(
    "RUNG61_CORPUS_SHA", "3c062f56e636ca43f4e537e9d6bf7b65b37f8f4652408e7f2581d94765fb15d6")
EPOCHS_ARM = 5  # rung 42's schedule, held fixed

SMOKE = os.environ.get("RUNG61_SMOKE", "1") == "1"
SHUTDOWN = os.environ.get("RUNG61_SHUTDOWN_CMD", "")

os.environ.setdefault("HF_HOME", str(STORE / "hf_cache"))
os.environ.setdefault("HF_HUB_OFFLINE", "1")
os.environ.setdefault("TRANSFORMERS_OFFLINE", "1")
os.environ.setdefault("CUDA_VISIBLE_DEVICES", "0")  # ONE GPU. The box is shared.

# The `swift` console script carries `#!/data/uaq_user/envs/...` from pip-install time, and
# /data has not existed since the 18-Aug reboot — exec fails with a bare ENOENT that reads
# as "swift is not installed". A shim with a LIVE shebang, ahead of it on PATH, for this run
# only: patching the env would change a shared artifact every other rung compares against.
SHIM = RUNG / "code" / "bin"
SHIM.mkdir(parents=True, exist_ok=True)
_sw = SHIM / "swift"
_sw.write_text(
    f"#!{sys.executable}\nimport sys\nfrom swift.cli.main import cli_main\nsys.exit(cli_main())\n"
)
_sw.chmod(0o755)
os.environ["PATH"] = (
    f"{SHIM}{os.pathsep}{Path(sys.executable).parent}{os.pathsep}" + os.environ.get("PATH", "")
)

for p in (REPO / "src", REPO / "vendor/orena-focus/src",
          REPO / "experiments/39-connector-lora/_models",
          REPO / "experiments/21-recipe-sweep/_models",
          REPO / "experiments/18-count-aug/_models",
          REPO / "experiments/16-count-probes/_models",
          REPO / "experiments/06-vit-lora/_models",
          REPO / "experiments/02-lora-sft/_models"):
    if p.is_dir():
        sys.path.insert(0, str(p))

import connector_lora_train as clt  # noqa: E402
import recipe_sweep_train as rst  # noqa: E402
import vit_lora_train as r06  # noqa: E402

# ── 🔴 THE INJECTION, and why it has to be here ─────────────────────────────────────────
# `ConnectorConfig` CARRIES the connector fields, but carrying them is not passing them.
# The only thing the trainer ever reads is `vit_lora_train._swift_args`, and there are two
# ways it gets set:
#
#   clt.train_to_step()   patches it to `swift_args_39`  — but ONLY inside the
#                         `stop_at_step is not None` branch, i.e. only when the supervisor
#                         that KILLS the run at a fixed step is armed.
#   rst.train_with_vram() patches it to `swift_args_21`  — unconditionally, and it runs
#                         last, so it wins.
#
# With `stop_at_step=None` — which is what an 8-epoch run needs — `clt.main` delegates
# straight to rung 21 and the connector never reaches the command line. Measured, not
# reasoned: the first gate run emitted `--freeze_aligner true --target_modules all-linear`,
# i.e. rung 06's recipe, while G3 sat there reporting a clean single variable. G3 tests the
# BUILDER; the trainer runs the LAUNCH. Substituting the name rung 21 reads makes the two
# agree, and G5 below checks the launch rather than trusting this comment.
# BOTH names have to move, and they move for different reasons:
#   `rst.swift_args_21` is what `train_with_vram` installs, so it decides the LAUNCH;
#   `r06._swift_args`   is what everything reads right now, so it decides what G5 can SEE.
# Patching only the first left G5 interrogating rung 06's untouched builder — which is
# exactly what it then reported, and it was right to.
rst.swift_args_21 = clt.swift_args_39
r06._swift_args = clt.swift_args_39

cfg = clt.ConnectorConfig(
    exp_dir=RUNG,
    run_name="61_all38_smoke" if SMOKE else "61_all38_ep5_v1",
    model_path=MODEL,
    data_root=STORE / "orena-data",
    manifest_path=REPO / "experiments/splits/frame_ood_v1.csv",
    control_train_jsonl=CORPUS,
    control_sha256=CORPUS_SHA,
    # ── rung 42's recipe, restated so a drift is VISIBLE rather than inherited ─────────
    learning_rate=2e-4, lora_rank=8, lora_alpha=32, vit_lr=None,
    num_train_epochs=EPOCHS_ARM,
    per_device_train_batch_size=1, gradient_accumulation_steps=16,
    seed=42, smoke=SMOKE, smoke_max_steps=4,
    # 🔴 The dataclass DEFAULT for this field is STEPS_PER_EPOCH (901). Left at the default
    # this rung would be shot in the head one epoch in, and `train_to_step` would record
    # that as a *supervised* termination — a killed run wearing a clean exit. `None` is what
    # makes `main` delegate to rung 21's full, unsupervised schedule.
    stop_at_step=None,
)
print(f"run_dir {cfg.run_dir}\nsmoke   {SMOKE}\nepochs  {EPOCHS_ARM}", flush=True)
print(f"freeze_aligner={cfg.freeze_aligner}  n_target_modules={len(cfg.target_modules)}", flush=True)

rows = [json.loads(line) for line in CORPUS.open(encoding="utf-8")]

# ── G1 — the corpus is the bytes we declared ─────────────────────────────────────────────
ds = clt.assert_dataset_is_the_controls(cfg)
assert ds["n_rows"] == 20667, f"expected 20,667 rows, got {ds['n_rows']}"
print(f"OK G1 dataset: {ds['n_rows']} rows, sha256 {ds['sha256'][:12]}..., "
      f"{ds['steps_per_epoch']:.1f} steps/epoch -> {ds['steps_per_epoch'] * EPOCHS_ARM:.0f} total",
      flush=True)

# ── G2 — every image on disk. A missing frame dies at step 0, not 30 h in ────────────────
imgs = [i for r in rows for i in r.get("images", [])]
# The prefix is asserted, not assumed: a relative path resolves against the CWD and would
# make the run depend on where it was launched from. UNAM serves /mnt, the pod /workspace.
IMG_ROOT = os.environ.get("RUNG61_IMG_ROOT", "/mnt/")
bad = [i for i in imgs if not i.startswith(IMG_ROOT) or not Path(i).exists()]
assert not bad, f"{len(bad)} unusable image paths, first: {bad[:3]}"
print(f"OK G2 images: {len(imgs)} paths over {len(set(imgs))} distinct, "
      f"all absolute under {IMG_ROOT}, all present", flush=True)

# ── G3 — SINGLE VARIABLE vs RUNG 42. Both sides built through the SAME builder ─────────
# rung 57's variable was the epoch count; this rung's is the corpus, so the control is
# rung 42's own 19,384-row file and the assertion moves with it.
R42_CORPUS = Path(os.environ.get(
    "RUNG61_R42_CORPUS", "/mnt/storage/uaq_user/rung57/corpus/train_19384_mntpaths.jsonl"))
a = clt._as_map_multi(clt.swift_args_39(
    replace(cfg, smoke=False, control_train_jsonl=R42_CORPUS)))
b = clt._as_map_multi(clt.swift_args_39(replace(cfg, smoke=False)))
diff = {k: (a.get(k), b.get(k)) for k in set(a) | set(b) if a.get(k) != b.get(k)}
for k, (x, y) in sorted(diff.items()):
    print(f"  {k:28s} r42={x}  ->  all38={y}")
assert set(diff) == {"--dataset"}, f"NOT single-variable vs rung 42: {sorted(diff)}"
assert cfg.num_train_epochs == 5, "rung 42 trained five epochs and that is not the variable"
print("OK G3 single-variable: only --dataset moves", flush=True)

# ── G3b — PROVENANCE. Every one of rung 42's 19,384 rows survives, unmodified ───────────
# 🔴 Without this, a corpus that REBUILT the shipped rows instead of appending to them
# would pass every other gate and quietly make the corpus, not the extra videos, the
# variable. Set equality on the serialised rows is the only check that catches it.
_r42 = {json.dumps(json.loads(l), sort_keys=True) for l in R42_CORPUS.open(encoding="utf-8")}
_mine = {json.dumps(r, sort_keys=True) for r in rows}
_lost = len(_r42 - _mine)
assert _lost == 0, f"🔴 {_lost} of rung 42's 19,384 rows are NOT in this corpus"
_new = len(_mine - _r42)
assert _new == 1283, f"expected exactly 1,283 new rows, got {_new}"
print(f"OK G3b provenance: all {len(_r42)} rung-42 rows present, {_new} new", flush=True)

# ── G4 — LEAK, recorded and INVERTED. 38 of 38 is the point of this rung ───────────────
# 🔴 rung 57 expected 30 of 38 and warned that its arm was legible only against rung 42.
# This rung expects 38 of 38, and the warning is stronger: NO local eval survives it. The
# number is asserted UPWARD so a corpus that quietly kept a video back is caught here.
_split42 = json.loads(Path(os.environ.get(
    "RUNG61_SPLIT42",
    str(REPO / "experiments/42-merged-corpus/RESULTS_split_42.json"))).read_text())
import re as _re
def _key(spec):
    d, v = spec.split("/", 1)
    return f"{d}__{_re.sub(r'[^A-Za-z0-9]+', '_', v).strip('_')}"
_all38 = {_key(v) for v in _split42["videos_promoted"] + _split42["videos_held_out"]}
assert len(_all38) == 38, len(_all38)
_stems = {"__".join(Path(i).name.split("__")[:2]) for i in imgs}
_covered = sorted(_all38 & _stems)
assert len(_covered) == 38, (
    f"🔴 only {len(_covered)} of the 38 test videos are in this corpus — the rung's whole "
    f"premise. Missing: {sorted(_all38 - _stems)}"
)
overlap = _covered
print(f"OK G4 coverage: all 38 test videos are in training. "
      f"🔴 NO LOCAL EVAL SURVIVES — bucket_mean on the 1,283 is now memorisation.", flush=True)

# ── G5 — the LAUNCH, not the builder ────────────────────────────────────────────────────
# 🔴 The gate that was missing, and whose absence would have cost 43 h of the wrong recipe.
# G3 proves `swift_args_39` is single-variable; it says NOTHING about which builder the
# trainer actually calls. This one interrogates the exact function `_train` will invoke,
# after every patch in this file has been applied, and asserts the connector survived.
launched = clt._as_map_multi(r06._swift_args(replace(cfg, smoke=False)))
assert launched.get("--freeze_aligner") == ("false",), (
    f"🔴 the LAUNCHED argv carries --freeze_aligner {launched.get('--freeze_aligner')}; "
    "rung 42 trains the aligner and this arm must too"
)
launched_targets = launched.get("--target_modules", ())
missing = [m for m in clt.MERGER_TARGETS if m not in launched_targets]
assert not missing, f"🔴 the LAUNCHED argv is missing {len(missing)} merger layers: {missing}"
assert "all-linear" in launched_targets, (
    "🔴 the LAUNCHED argv lost 'all-linear' — the merger names ALONE drop the 504 LLM and "
    "216 ViT tensors and train the connector in isolation"
)
assert launched.get("--num_train_epochs") == (str(EPOCHS_ARM),), (
    f"🔴 the LAUNCHED argv says {launched.get('--num_train_epochs')} epochs, not {EPOCHS_ARM}"
)
print(f"OK G5 launch: --freeze_aligner false, {len(launched_targets)} target_modules "
      f"(all-linear + {len(clt.MERGER_TARGETS)} merger), --num_train_epochs {EPOCHS_ARM}", flush=True)

cfg.run_dir.mkdir(parents=True, exist_ok=True)
(cfg.run_dir / "argv.json").write_text(json.dumps(r06._swift_args(replace(cfg, smoke=False)), indent=1))
(cfg.run_dir / "diff_vs_r42.json").write_text(json.dumps({k: list(v) for k, v in diff.items()}, indent=1))
(cfg.run_dir / "gates.json").write_text(json.dumps(
    {"corpus_sha256": ds["sha256"], "n_rows": ds["n_rows"], "n_images": len(imgs),
     "n_distinct_images": len(set(imgs)), "steps_per_epoch": ds["steps_per_epoch"],
     "total_steps": ds["steps_per_epoch"] * EPOCHS_ARM, "epochs": EPOCHS_ARM,
     "freeze_aligner": cfg.freeze_aligner, "n_target_modules": len(cfg.target_modules),
     "test_videos_in_corpus": overlap, "n_test_videos": 38}, indent=1))
(cfg.run_dir / "pip_freeze.txt").write_text(
    subprocess.run([sys.executable, "-m", "pip", "freeze"], capture_output=True, text=True).stdout)

t0 = time.perf_counter()
rc = 0
try:
    out = clt.main(cfg, "train")
    print(f"\ntrained in {(time.perf_counter() - t0) / 3600:.2f} h -> {out}", flush=True)
except BaseException as exc:  # noqa: BLE001 — the RC must be written on every exit path
    rc = 1
    print(f"\nTRAIN FAILED after {(time.perf_counter() - t0) / 3600:.2f} h: {exc!r}", flush=True)
    raise
finally:
    # The REAL return code, expanded. rung 54's harness wrote the LITERAL `$rc` and a 0-byte
    # log, so its merge captured no return code at all and its guard could not have warned.
    (cfg.run_dir / "TRAIN_RC").write_text(
        f"TRAIN_RC={rc}\nELAPSED_H={(time.perf_counter() - t0) / 3600:.3f}\n"
    )
    if SHUTDOWN:
        # Set only on a rented pod. Unset on UNAM, so nothing here can shut the box down.
        print(f"[shutdown] {SHUTDOWN}", flush=True)
        subprocess.run(SHUTDOWN, shell=True)
